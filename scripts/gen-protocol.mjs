#!/usr/bin/env node
// Regenerates packages/protocol/src/generated from the Rust protocol crate.
//
//   1. clears the generated dir (so removed Rust types disappear),
//   2. runs `cargo test -p orkestr-protocol export_bindings` (ts-rs export,
//      TS_RS_EXPORT_DIR is set in .cargo/config.toml),
//   3. writes generated/index.ts, a barrel re-exporting every generated module.
//
// Usage: npm run gen:protocol

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { delimiter, dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "packages", "protocol", "src", "generated");

function log(msg) {
  process.stdout.write(`[gen:protocol] ${msg}\n`);
}

// Make sure cargo is reachable even when ~/.cargo/bin is not on PATH (Git Bash on Windows).
const env = { ...process.env };
const cargoBin = join(homedir(), ".cargo", "bin");
if (existsSync(cargoBin)) {
  // Windows env keys are case-insensitive ("Path"); reuse the existing key.
  const pathKey = Object.keys(env).find((k) => k.toUpperCase() === "PATH") ?? "PATH";
  env[pathKey] = `${cargoBin}${delimiter}${env[pathKey] ?? ""}`;
}

log(`clearing ${relative(root, outDir)}`);
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

log("running cargo test -p orkestr-protocol export_bindings");
const result = spawnSync("cargo", ["test", "-p", "orkestr-protocol", "--quiet", "export_bindings"], {
  cwd: root,
  env,
  stdio: "inherit",
});
if (result.status !== 0) {
  log("cargo test failed");
  process.exit(result.status ?? 1);
}

function collect(dir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      out.push(...collect(full));
    } else if (name.endsWith(".ts") && name !== "index.ts") {
      out.push(full);
    }
  }
  return out;
}

const modules = collect(outDir).map((f) => "./" + relative(outDir, f).replace(/\\/g, "/").replace(/\.ts$/, ""));
if (modules.length === 0) {
  log("no bindings were generated");
  process.exit(1);
}
const barrel =
  "// This file was generated by scripts/gen-protocol.mjs. Do not edit this file manually.\n" +
  modules.map((m) => `export * from "${m}";`).join("\n") +
  "\n";
writeFileSync(join(outDir, "index.ts"), barrel);
log(`wrote ${modules.length} modules + index.ts`);
