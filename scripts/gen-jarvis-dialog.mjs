export function normalize(s) {
  const words = s
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^\p{L}\p{N}+']+/gu, " ")
    .split(/\s+/)
    .filter(Boolean)
    .map((w) => (w === "оркестр" || w === "оркестра" || w === "оркестре" || w === "оркестром" || w === "orkestr" ? "orkapp" : w))
    .filter((w) => !FILLERS.has(w) && !DIALOG_FILLERS.has(w));
  return words.join(" ");
}

// ---------------------------------------------------------------------------
// Template expansion
// ---------------------------------------------------------------------------

function parse(src) {
  let i = 0;
  function seq(stop) {
    const parts = [[""]];
    let buf = "";
    const flush = () => {
      if (buf) parts.push([buf]);
      buf = "";
    };
    while (i < src.length && !stop.includes(src[i])) {
      const c = src[i];
      if (c === "(" || c === "[") {
        flush();
        i++;
        const alts = [];
        for (;;) {
          alts.push(seq(c === "(" ? "|)" : "|]"));
          const end = src[i++];
          if (end === ")" || end === "]") break;
        }
        const flat = alts.flat();
        parts.push(c === "[" ? ["", ...flat] : flat);
      } else {
        buf += c;
        i++;
      }
    }
    flush();
    // cartesian product
    let out = [""];
    for (const p of parts) {
      const next = [];
      for (const a of out) for (const b of p) next.push(a + b);
      out = next;
      if (out.length > 20000) throw new Error(`template too large: ${src}`);
    }
    return out;
  }
  const r = seq("");
  return r.map((s) => s.replace(/\s+/g, " ").replace(/\s+([,?!.])/g, "$1").trim()).filter(Boolean);
}

// ---------------------------------------------------------------------------
// Seeded randomness (deterministic output)
// ---------------------------------------------------------------------------

function hash(s) {
  let h = 2166136261;
  for (const ch of s) {
    h ^= ch.codePointAt(0);
    h = Math.imul(h, 16777619) >>> 0;
  }
  return h;
}

/** Typo variant of a phrase (adjacent swap / dropped letter / е↔и) in one ≥5-letter word, or null. */
function typo(phrase) {
  const words = phrase.split(" ");
  const idx = words.map((w, i) => [w, i]).filter(([w]) => [...w].length >= 6 && /^\p{L}+$/u.test(w));
  if (idx.length === 0) return null;
  const h = hash(phrase);
  const [w, i] = idx[h % idx.length];
  const ch = [...w];
  const k = 1 + (h >>> 8) % (ch.length - 2);
  switch ((h >>> 16) % 3) {
    case 0:
      [ch[k], ch[k + 1]] = [ch[k + 1], ch[k]];
      break;
    case 1:
      ch.splice(k, 1);
      break;
    default: {
      const map = { е: "и", и: "е", о: "а", а: "о" };
      const j = ch.findIndex((c, n) => n > 0 && map[c]);
      if (j < 0) return null;
      ch[j] = map[ch[j]];
    }
  }
  const out = ch.join("");
  if (out === w) return null;
  words[i] = out;
  return words.join(" ");
}

