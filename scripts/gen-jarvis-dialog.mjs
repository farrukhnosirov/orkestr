// ---------------------------------------------------------------------------
// Build
// ---------------------------------------------------------------------------

const intents = [];
const owner = new Map(); // normalized → intent id
const conflicts = [];
const held = [];
let typoCount = 0;
let heldTypo = 0;

for (const [category, list] of Object.entries(CATEGORIES)) {
  for (const it of list) {
    const opens = it.open ?? ASK_SHORT;
    const tails = it.tail ?? [""];
    const raw = [];
    for (const tpl of it.q) for (const base of parse(tpl)) for (const o of opens) for (const tail of tails) raw.push(`${o}${base}${tail}`);
    const questions = [];
    const seenHere = new Set();
    for (const phrase of raw) {
      const key = normalize(phrase);
      if (!key || seenHere.has(key)) continue;
      const prev = owner.get(key);
      if (prev && prev !== it.id) {
        conflicts.push(`${phrase} → ${prev} / ${it.id}`);
        continue;
      }
      seenHere.add(key);
      owner.set(key, it.id);
      // ~8% held out for the accuracy test (never in the bank)
      if (hash(`held:${key}`) % 100 < 8) {
        held.push({ text: phrase, intent: it.id });
        const tv = typo(phrase);
        if (tv && normalize(tv) !== key) {
          held.push({ text: tv, intent: it.id, typo: true });
          heldTypo++;
        }
        continue;
      }
      questions.push(phrase);
    }
    // a few typo variants (seeded), counted separately
    const typos = [];
    for (const q of questions) {
      if (hash(`typo:${q}`) % 100 >= 6) continue;
      const tv = typo(q);
      if (!tv) continue;
      const key = normalize(tv);
      if (owner.has(key)) continue;
      owner.set(key, it.id);
      typos.push(tv);
    }
    typoCount += typos.length;
    if (it.a.length === 0) throw new Error(`${it.id}: no answers`);
    const entry = { id: it.id, category, questions: [...questions, ...typos], answers: it.a };
    if (it.action) entry.action = it.action;
    intents.push(entry);
  }
}

const questions = intents.reduce((n, i) => n + i.questions.length, 0);
const answers = intents.reduce((n, i) => n + i.answers.length, 0);
const unique = questions - typoCount;
const out = {
  format: "orkestr.jarvis-dialog",
  version: 1,
  lang: "ru",
  generatedBy: "scripts/gen-jarvis-dialog.mjs",
  stats: { intents: intents.length, questions, uniquePhrasings: unique, typoVariants: typoCount, answers, heldOut: held.length },
  intents,
};
const heldOut = { format: "orkestr.jarvis-dialog-heldout", version: 1, items: held };

// one intent / item per line: compact, still diff-friendly
const lines = (arr) => arr.map((x) => JSON.stringify(x)).join(",\n");
const { intents: _all, ...head } = out;
const json = `${JSON.stringify(head).slice(0, -1)},"intents":[\n${lines(intents)}\n]}\n`;
const heldJson = `{"format":"${heldOut.format}","version":1,"items":[\n${lines(held)}\n]}\n`;
if (process.argv.includes("--check")) {
  const cur = readFileSync(OUT, "utf8");
  if (cur !== json) {
    console.error("dialog.json is out of date: run node scripts/gen-jarvis-dialog.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(OUT, json);
  writeFileSync(HELD, heldJson);
}
console.log(
  `[gen-jarvis-dialog] ${intents.length} intents, ${unique} unique phrasings (+${typoCount} typo variants = ${questions} questions), ${answers} answers, ${held.length} held out (${heldTypo} typos), ${conflicts.length} cross-intent duplicates dropped`,
);
if (process.argv.includes("--conflicts")) for (const c of conflicts) console.log("  conflict:", c);
if (unique < 10000) {
  console.error(`expected ≥ 10000 unique phrasings, got ${unique}`);
  process.exit(1);
}
